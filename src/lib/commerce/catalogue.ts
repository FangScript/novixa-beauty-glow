const grooming = (
  base: Omit<Product, "category" | "images"> & { gender: Gender; images?: string[] },
): Product => ({
  ...base,
  category: "grooming",
  images: base.images ?? [accessoriesCategory],
  tags: base.tags,
});
const bundle = (base: any): Product => ({
  ...base,
  category: "bundle",
  gender: "unisex",
  images: base.images ?? [bundleProduct],
  tags: base.tags,
});

