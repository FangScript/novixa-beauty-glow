import { z } from "zod";
const perfumeProduct = "/images/product-perfume.jpg";
const bundleProduct = "/images/product-bundle.jpg";
const brushesProduct = "/images/product-brushes.jpg";
const spongesProduct = "/images/product-sponges.jpg";
const perfumeCategory = "/images/category-perfume.jpg";
const makeupCategory = "/images/category-makeup.jpg";
const accessoriesCategory = "/images/category-accessories.jpg";

export const productCategorySchema = z.enum([
  "perfume",
  "makeup",
  "grooming",
  "bundle",
  "accessories",
]);
export const genderSchema = z.enum(["men", "women", "unisex"]);
export const productSchema = z
  .object({
    id: z.string().min(1),
    name: z.string().min(2),
    slug: z.string().regex(/^[a-z0-9-]+$/),
    description: z.string().min(10),
    price: z.number().positive(),
    salePrice: z.number().positive().optional(),
    gender: genderSchema,
    category: productCategorySchema,
    brand: z.string().min(1),
    sku: z.string().min(3),
    images: z.array(z.string()).min(1),
    fragranceFamily: z.string().optional(),
    topNotes: z.array(z.string()).optional(),
    middleNotes: z.array(z.string()).optional(),
    baseNotes: z.array(z.string()).optional(),
    occasion: z.array(z.string()).optional(),
    longevity: z.string().optional(),
    shade: z.string().optional(),
    finish: z.string().optional(),
    coverage: z.string().optional(),
    skinType: z.string().optional(),
    hairType: z.string().optional(),
    ingredients: z.array(z.string()).optional(),
    stock: z.number().int().nonnegative(),
    rating: z.number().min(0).max(5),
    reviewCount: z.number().int().nonnegative(),
    badge: z.string().optional(),
    tags: z.array(z.string()),
  })
  .refine((product) => !product.salePrice || product.salePrice < product.price, {
    message: "Sale price must be lower than regular price",
    path: ["salePrice"],
  });
export type Gender = z.infer<typeof genderSchema>;
export type ProductCategory = z.infer<typeof productCategorySchema>;
export type Product = z.infer<typeof productSchema>;

